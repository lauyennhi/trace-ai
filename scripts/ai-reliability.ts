/**
 * Prints how well the AI's process score agrees with the teacher's grade, and how stable it is when the same work
 * is graded again. Talks to a RUNNING server; the stability part needs a real GEMINI_API_KEY (about 6 AI calls).
 *
 *   npx tsx scripts/ai-reliability.ts              # BASE=http://localhost:3000, teacher hung.nguyen@edu.vn
 */
const BASE = process.env.BASE || "http://localhost:3000";
const call = async (path: string, token: string | null, body?: any) => {
  const res = await fetch(BASE + path, { method: body ? "POST" : "GET", headers: { "content-type": "application/json", ...(token ? { authorization: `Bearer ${token}` } : {}) }, body: body ? JSON.stringify(body) : undefined });
  const j: any = await res.json().catch(() => ({}));
  if (!j.success) throw new Error(`${path}: ${j.message || res.status}`);
  return j.data;
};
const main = async () => {
  const token = (await call("/api/auth/login", null, { email: process.env.EMAIL || "hung.nguyen@edu.vn", password: process.env.PASSWORD || "123456" })).token;
  const r = await call("/api/analytics/ai-reliability", token);
  const o = r.overall;
  console.log(`AI vs teacher  n=${o.n}  mean abs diff=${o.mae}  within ±1=${o.within1 === null ? "-" : Math.round(o.within1 * 100) + "%"}  bias=${o.bias}  correlation=${o.pearson}`);
  if (r.demo) console.log("  (demo data: generated by the system, NOT real results)");
  if (o.n < r.min_recommended) console.log(`  (only ${o.n} graded submissions; ${r.min_recommended}+ needed before drawing conclusions)`);
  for (const c of r.by_course) console.log(`  - ${c.course}: n=${c.n}, diff=${c.mae}, within ±1=${c.within1 === null ? "-" : Math.round(c.within1 * 100) + "%"}`);
  try {
    const ids: string[] = await call("/api/analytics/ai-reliability/sample", token);
    const t = await call("/api/analytics/ai-retest", token, { submission_ids: ids, runs: 3 });
    console.log("\nStability (same work graded 3 times, nothing saved):");
    for (const x of t.results) console.log(`  ${x.title}: ${x.scores.join(", ")}  sd=${x.sd}  range=${x.range}`);
  } catch (e: any) { console.log("\nStability test skipped:", e.message); }
};
main().catch((e) => { console.error(e.message); process.exit(1); });
